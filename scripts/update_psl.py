#!/usr/bin/env python3
"""Regenerate extensions/chromecli/psl-data.js from the Public Suffix List (ICANN + private sections).

    curl -fsSL https://publicsuffix.org/list/public_suffix_list.dat -o /tmp/psl.dat
    python3 scripts/update_psl.py /tmp/psl.dat

Rules are stored as Chrome sees hostnames: lowercase ASCII, IDN labels as punycode (xn--). The extension never fetches
the list itself (no remote code or data); a refresh is a reviewed commit and an extension reload.
"""
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "extensions" / "chromecli" / "psl-data.js"


def ascii_rule(rule: str) -> str | None:
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    labels = []
    for label in rule.split("."):
        if label == "*" or label.isascii():
            labels.append(label.lower())
            continue
        try:
            labels.append("xn--" + label.encode("punycode").decode("ascii"))
        except Exception:  # noqa: BLE001 - skip a rule that can't be encoded
            return None
    out = prefix + ".".join(labels)
    return out if re.fullmatch(r"!?(\*\.)?[a-z0-9.-]+", out) else None


def main(src: str) -> None:
    text = Path(src).read_text(encoding="utf-8")
    version = re.search(r"^// VERSION: (\S+)", text, re.M)
    commit = re.search(r"^// COMMIT: (\S+)", text, re.M)
    rules = []
    for line in text.splitlines():
        line = line.strip().split()[0] if line.strip() else ""
        if not line or line.startswith("//"):
            continue
        r = ascii_rule(line)
        if r:
            rules.append(r)
    rules = sorted(set(rules))
    OUT.write_text(
        "// Generated by scripts/update_psl.py from https://publicsuffix.org/list/public_suffix_list.dat; do not edit.\n"
        "// The Public Suffix List is subject to the terms of the Mozilla Public License, v. 2.0\n"
        "// (https://mozilla.org/MPL/2.0/).\n"
        f"export const PSL_VERSION = {json.dumps((version.group(1) if version else '') + (' ' + commit.group(1)[:12] if commit else ''))};\n"
        f"export const PSL_RULES = {json.dumps(chr(10).join(rules))};\n",
        encoding="utf-8")
    print(f"{OUT}: {len(rules)} rules")


if __name__ == "__main__":
    main(sys.argv[1])
